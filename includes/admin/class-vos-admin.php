<?php

class VOS_Admin {

    protected $display;
    protected $settings;
    protected $helpers;

    public function __construct() {

        $this->load_dependencies();
        $this->set_controllers();

    }

    private function load_dependencies() {

        require_once VOS_TM_PATH . 'includes/admin/class-vos-admin-helpers.php';
        require_once VOS_TM_PATH . 'includes/admin/class-vos-admin-display.php';
        require_once VOS_TM_PATH . 'includes/admin/class-vos-settings.php';

    }

    private function set_controllers() {

        $this->display  = new VOS_Admin_Display();
        $this->settings = new VOS_Settings();
        $this->helpers  = new VOS_Admin_Helpers();

    }

    public function add_user_roles() {

        // Retire the legacy role name from early versions of the plugin.
        remove_role( 'territory-manager' );

        // Always re-seed the Map Manager role so its display name and
        // baseline caps stay current across plugin updates (if the role
        // already existed, remove_role + add_role rewrites the definition;
        // existing user assignments persist because they're stored by
        // role slug in user meta, not by role object).
        remove_role( 'vos_territory_manager' );
        add_role(
            'vos_territory_manager',
            'Map Manager',
            array( 'read' => true )
        );

        $caps      = self::map_editor_caps();
        $privileged = array( 'administrator', 'vos_territory_manager' );

        // Grant the full map + branch cap set to admins and to the
        // dedicated Map Manager role.
        foreach ( $privileged as $role_name ) {
            $role = get_role( $role_name );
            if ( ! $role ) continue;
            foreach ( $caps as $cap ) {
                if ( ! $role->has_cap( $cap ) ) {
                    $role->add_cap( $cap );
                }
            }
        }

        // Revoke these caps from every other role. Prior plugin versions
        // blanket-granted edit_vos_territory to every role on init, which
        // defeated the purpose of a dedicated map-editor role. This scrubs
        // that legacy grant on upgrade.
        foreach ( wp_roles()->roles as $role_name => $role_info ) {
            if ( in_array( $role_name, $privileged, true ) ) continue;
            $role = get_role( $role_name );
            if ( ! $role ) continue;
            foreach ( $caps as $cap ) {
                if ( $role->has_cap( $cap ) ) {
                    $role->remove_cap( $cap );
                }
            }
        }

    }

    /**
     * Returns every capability the Map Manager workflow needs. Used both
     * to seed roles on init and — indirectly — by the admin menu, REST
     * routes, and branch CPT, which all gate on members of this set.
     */
    public static function map_editor_caps() {

        return array(
            // Gates the Territory Map admin page, REST write routes, and
            // the JSON import handler.
            'edit_vos_territory',

            // Primitive caps generated by the vos_branch CPT's custom
            // capability_type => [vos_branch, vos_branches] with
            // map_meta_cap => true. Needed for full branch CRUD without
            // granting 'edit_posts' (which would unlock Posts too).
            'edit_vos_branches',
            'edit_others_vos_branches',
            'edit_private_vos_branches',
            'edit_published_vos_branches',
            'publish_vos_branches',
            'read_private_vos_branches',
            'delete_vos_branches',
            'delete_others_vos_branches',
            'delete_private_vos_branches',
            'delete_published_vos_branches',
            'create_vos_branches',

            // Playground CPT primitive caps — mirror the branch set so the
            // same roles (admin + Map Manager) can CRUD playgrounds.
            'edit_vos_playgrounds',
            'edit_others_vos_playgrounds',
            'edit_private_vos_playgrounds',
            'edit_published_vos_playgrounds',
            'publish_vos_playgrounds',
            'read_private_vos_playgrounds',
            'delete_vos_playgrounds',
            'delete_others_vos_playgrounds',
            'delete_private_vos_playgrounds',
            'delete_published_vos_playgrounds',
            'create_vos_playgrounds',

            // Required for featured images on the Branch edit screen.
            'upload_files',
        );

    }

    public function register_blocks() {

        // --- Territory Map block -------------------------------------------
        $tm_asset_file = VOS_TM_PATH . 'build/territory-map-block.asset.php';
        $tm_asset      = file_exists( $tm_asset_file ) ? include $tm_asset_file : array(
            'dependencies' => array( 'wp-blocks', 'wp-element', 'wp-block-editor' ),
            'version'      => null,
        );

        wp_register_script(
            'vos-territory-block',
            VOS_TM_URL . 'build/territory-map-block.js',
            $tm_asset['dependencies'],
            $tm_asset['version'],
            true
        );

        register_block_type( 'vos/territory-map', array(
            'editor_script'   => 'vos-territory-block',
            'render_callback' => array( $this, 'render_territory_map_block' ),
        ) );

        // --- Branch Finder block -------------------------------------------
        $bf_asset_file = VOS_TM_PATH . 'build/branch-finder-block.asset.php';
        $bf_asset      = file_exists( $bf_asset_file ) ? include $bf_asset_file : array(
            'dependencies' => array( 'wp-blocks', 'wp-element', 'wp-block-editor' ),
            'version'      => null,
        );

        wp_register_script(
            'vos-branch-finder-block',
            VOS_TM_URL . 'build/branch-finder-block.js',
            $bf_asset['dependencies'],
            $bf_asset['version'],
            true
        );

        register_block_type( 'vos/branch-finder', array(
            'editor_script'   => 'vos-branch-finder-block',
            'render_callback' => array( $this, 'render_branch_finder_block' ),
        ) );

    }

    /**
     * Frontend output for the Territory Map block.
     * The public JS mounts the React map onto this div.
     */
    public function render_territory_map_block() {
        return '<div id="vos-territory-public"></div>';
    }

    /**
     * Frontend output for the Branch Finder block.
     * Uses a class (not ID) so the same block can appear more than once
     * on a page — src/index.js mounts on every .vos-branch-finder node.
     */
    public function render_branch_finder_block() {
        return '<div class="vos-branch-finder"></div>';
    }

    public function run() {

        add_action( 'init', array( $this, 'add_user_roles' ) );
        add_action( 'init', array( $this, 'register_blocks' ) );

        add_action( 'admin_init', array( $this->settings, 'register' ) );

        add_action( 'admin_menu', array( $this->settings, 'add_settings_page' ) );

        add_action( 'admin_enqueue_scripts', array( $this->display, 'enqueue_styles_scripts' ) );

        add_action( 'wp_enqueue_scripts', array( $this->display, 'enqueue_styles_scripts' ) );

        add_action( 'admin_post_save_vos_tm_settings', array( $this->settings, 'save_settings' ) );

        add_action( 'admin_post_vos_tm_import_json',   array( $this->settings, 'handle_import' ) );

        add_action( 'admin_post_vos_tm_save_maptiler_key', array( $this->settings, 'save_maptiler_key' ) );

        add_action( 'rest_api_init', array( $this->settings, 'register_rest_routes' ) );

    }

}
